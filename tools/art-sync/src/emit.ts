import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * The prototype's art scripts, in the order the prototype loads them. The six generators come
 * first (each one's boot waits for the one before); `yap-dc` holds the viseme mapping (`mouthFor`)
 * and the blink rhythm, `yap-voice` the recorded-line player whose timing the lipsync follows.
 */
export const SCRIPTS = [
  { file: 'yap-art.js', name: 'yapArt' },
  { file: 'yap-cast.js', name: 'yapCast' },
  { file: 'yap-sticker.js', name: 'yapSticker' },
  { file: 'yap-r4.js', name: 'yapR4' },
  { file: 'yap-r5.js', name: 'yapR5' },
  { file: 'yap-r6.js', name: 'yapR6' },
  { file: 'yap-dc.js', name: 'yapDc' },
  { file: 'yap-voice.js', name: 'yapVoice' },
] as const;

/** The browser globals the scripts read, handed to each one by the art runtime. */
export const GLOBALS = [
  'window',
  'document',
  'Path2D',
  'DOMMatrix',
  'setTimeout',
  'clearTimeout',
  'performance',
  'fetch',
  'Audio',
  'speechSynthesis',
  'SpeechSynthesisUtterance',
] as const;

export const REPO_ROOT = join(import.meta.dirname, '../../..');
export const SOURCE_DIR = join(REPO_ROOT, 'design/prototype/art');
export const GENERATED_DIR = join(REPO_ROOT, 'packages/art/src/generated');

export const SCRIPT_BEGIN = '/* ---- prototype script, verbatim ---- */';
export const SCRIPT_END = '/* ---- end of prototype script ---- */';

export interface GeneratedFile {
  name: string;
  text: string;
}

const HEADER = (from: string) => [
  `// GENERATED by tools/art-sync from ${from}. Do not edit.`,
  '// Change the prototype, then run `pnpm --filter @yapling/art-sync sync`; CI fails while this',
  '// file is out of date (`pnpm --filter @yapling/art-sync check`). Between the markers is the',
  "// prototype's script byte for byte; around it, only the module wrapper is added: the script runs",
  '// inside `load`, against the browser globals the art runtime passes in.',
];

export const moduleName = (file: string) => `${file.replace(/\.js$/, '')}.generated.ts`;

/** One script as a module: `load(globals)` runs it, verbatim, against the given globals. */
export function renderModule(file: string, source: string): string {
  return [
    ...HEADER(`design/prototype/art/${file}`),
    '// @ts-nocheck',
    "import type { PrototypeGlobals } from '../runtime/globals';",
    '',
    `export const source = 'design/prototype/art/${file}';`,
    '',
    'export function load(globals: PrototypeGlobals): void {',
    `  const { ${GLOBALS.join(', ')} } = globals;`,
    SCRIPT_BEGIN,
    source.replace(/\n$/, ''),
    SCRIPT_END,
    '}',
    '',
  ].join('\n');
}

/** The index: every script's `load`, in load order. */
export function renderIndex(): string {
  return [
    ...HEADER('design/prototype/art/'),
    "import type { PrototypeGlobals } from '../runtime/globals';",
    ...SCRIPTS.map(
      (s) => `import { load as ${s.name} } from './${moduleName(s.file).replace(/\.ts$/, '')}';`,
    ),
    '',
    '/** The scripts in the order the prototype loads them. */',
    'export const SCRIPTS: readonly { file: string; load: (globals: PrototypeGlobals) => void }[] = [',
    ...SCRIPTS.map((s) => `  { file: '${s.file}', load: ${s.name} },`),
    '];',
    '',
  ].join('\n');
}

/** Every generated file as a fresh sync would write it, read from `design/prototype/art/`. */
export function renderAll(sourceDir = SOURCE_DIR): GeneratedFile[] {
  return [
    ...SCRIPTS.map((s) => ({
      name: moduleName(s.file),
      text: renderModule(s.file, readFileSync(join(sourceDir, s.file), 'utf8')),
    })),
    { name: 'index.generated.ts', text: renderIndex() },
  ];
}
