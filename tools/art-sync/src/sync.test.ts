import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import {
  GENERATED_DIR,
  moduleName,
  renderModule,
  SCRIPT_BEGIN,
  SCRIPT_END,
  SCRIPTS,
  SOURCE_DIR,
} from './emit';
import { sync } from './sync';

const temps: string[] = [];
const temp = () => {
  const dir = mkdtempSync(join(tmpdir(), 'art-sync-'));
  temps.push(dir);
  return dir;
};
afterEach(() => {
  for (const dir of temps.splice(0)) rmSync(dir, { recursive: true, force: true });
});

describe('the generated art modules', () => {
  it('are current with design/prototype/art (run `pnpm --filter @yapling/art-sync sync`)', () => {
    expect(sync({ check: true }).stale).toEqual([]);
  });

  it.each(SCRIPTS)("carry $file's script byte for byte", ({ file }) => {
    const source = readFileSync(join(SOURCE_DIR, file), 'utf8');
    const generated = readFileSync(join(GENERATED_DIR, moduleName(file)), 'utf8');
    const start = generated.indexOf(SCRIPT_BEGIN) + SCRIPT_BEGIN.length + 1;
    const end = generated.indexOf(SCRIPT_END) - 1;
    expect(generated.slice(start, end)).toBe(source.replace(/\n$/, ''));
  });

  it('marks every module as generated', () => {
    const text = renderModule('x.js', '(function(){})();\n');
    expect(text.split('\n')[0]).toMatch(/^\/\/ GENERATED by tools\/art-sync .*Do not edit\./);
  });
});

describe('the check', () => {
  it('reports a changed script, a hand edit and a stray file, and a sync repairs them', () => {
    const dir = temp();
    expect(sync({ dir }).written).toHaveLength(SCRIPTS.length + 1);
    expect(sync({ dir, check: true }).stale).toEqual([]);

    const edited = join(dir, moduleName('yap-cast.js'));
    writeFileSync(edited, readFileSync(edited, 'utf8').replace("label:'Cat'", "label:'Kat'"));
    writeFileSync(join(dir, 'stray.generated.ts'), '');
    expect(sync({ dir, check: true }).stale.sort()).toEqual(
      [moduleName('yap-cast.js'), 'stray.generated.ts'].sort(),
    );

    const fixed = sync({ dir });
    expect(fixed.written).toEqual([moduleName('yap-cast.js')]);
    expect(fixed.removed).toEqual(['stray.generated.ts']);

    const sources = temp();
    for (const s of SCRIPTS) {
      const text = readFileSync(join(SOURCE_DIR, s.file), 'utf8');
      writeFileSync(join(sources, s.file), s.file === 'yap-r6.js' ? `${text}// changed\n` : text);
    }
    expect(sync({ dir, sourceDir: sources, check: true }).stale).toEqual([moduleName('yap-r6.js')]);
  });
});
