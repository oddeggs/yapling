/**
 * Builds `src/catalogues.generated.ts`: one import per `<feature>.<language>.ts` in `src`, merged
 * into one catalogue per language. `generate-catalogues.ts` writes it; a test compares it with the
 * committed file.
 *
 * Metro (the app), Vite (Vitest) and esbuild (the Worker) share no glob import, so
 * the index is plain static imports written by this script.
 */
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

import { languages, sourceLanguage } from '../src/catalogue-types';

export const generatedFileName = 'catalogues.generated.ts';

/** A feature's catalogue files, as found on disk. */
export interface CatalogueFiles {
  /** The file stem: `real-week`. */
  readonly file: string;
  /** The key prefix and export stem: `realWeek`. */
  readonly name: string;
}

const kebabStem = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;

export function exportStem(file: string): string {
  return file.replace(/-([a-zA-Z0-9])/g, (_match, letter: string) => letter.toUpperCase());
}

/** `en` → `En`, `pt-br` → `PtBr`, `zh-Hans` → `ZhHans`: the suffix of a catalogue's export name. */
export function languageSuffix(language: string): string {
  const stem = exportStem(language);
  return stem.charAt(0).toUpperCase() + stem.slice(1);
}

/** The features in a folder, sorted by file name; throws when a language file is missing or misnamed. */
export function findCatalogueFiles(
  dir: string,
  shipped: readonly string[] = languages,
): CatalogueFiles[] {
  const stems = new Map<string, Set<string>>(shipped.map((l) => [l, new Set()]));
  const fileName = new RegExp(`^(.+)\\.(${shipped.join('|')})\\.ts$`);
  for (const name of readdirSync(dir)) {
    if (name.endsWith('.test.ts') || name.endsWith('.generated.ts')) continue;
    const m = fileName.exec(name);
    if (!m) continue;
    const [, stem = '', language = ''] = m;
    if (!kebabStem.test(stem))
      throw new Error(`${name}: name catalogue files <feature>.${language}.ts in kebab-case`);
    stems.get(language)?.add(stem);
  }
  const source = stems.get(sourceLanguage) ?? new Set<string>();
  for (const [language, set] of stems) {
    for (const stem of source)
      if (!set.has(stem))
        throw new Error(`${stem}.${sourceLanguage}.ts has no ${stem}.${language}.ts`);
    for (const stem of set)
      if (!source.has(stem))
        throw new Error(`${stem}.${language}.ts has no ${stem}.${sourceLanguage}.ts`);
  }
  return [...source].sort().map((file) => {
    const name = exportStem(file);
    for (const language of shipped) {
      const exported = `${name}${languageSuffix(language)}`;
      const text = readFileSync(join(dir, `${file}.${language}.ts`), 'utf8');
      if (!new RegExp(`export const ${exported}\\b`).test(text))
        throw new Error(`${file}.${language}.ts must export const ${exported}`);
    }
    return { file, name };
  });
}

/** The source of the generated index for these features. */
export function catalogueIndexSource(
  features: readonly CatalogueFiles[],
  shipped: readonly string[] = languages,
): string {
  const imports = features.flatMap(({ file, name }) =>
    shipped.map((l) => `import { ${name}${languageSuffix(l)} } from './${file}.${l}';`),
  );
  const entries = features.map(
    ({ file, name }) =>
      `  { name: '${name}', file: '${file}', catalogues: { ${shipped
        .map((l) => `${/^\w+$/.test(l) ? l : `'${l}'`}: ${name}${languageSuffix(l)}`)
        .join(', ')} } },`,
  );
  const block = (lines: readonly string[]) =>
    lines.length === 0 ? '{}' : `{\n${lines.join('\n')}\n}`;
  const merged = shipped.flatMap((l) => [
    '',
    l === sourceLanguage
      ? `/** The source catalogue: every key, in ${l}. */`
      : `/** Every key, in ${l}. */`,
    `export const ${exportStem(l)} = ${block(features.map(({ name }) => `  ...${name}${languageSuffix(l)},`))};`,
  ]);
  return [
    '// Generated by `pnpm --filter @yapling/i18n gen` from the <feature>.<language>.ts files in',
    '// this folder. Do not edit; re-run the generator instead.',
    "import type { FeatureCatalogues } from './catalogue-types';",
    ...imports,
    '',
    '/** Every feature, in file-name order, with its catalogue in each language. */',
    `export const features: readonly FeatureCatalogues[] = ${entries.length === 0 ? '[]' : `[\n${entries.join('\n')}\n]`};`,
    ...merged,
    '',
    "/** Each language's merged catalogue. */",
    `export const catalogues = { ${shipped
      .map((l) => (exportStem(l) === l ? l : `'${l}': ${exportStem(l)}`))
      .join(', ')} };`,
    '',
  ].join('\n');
}

export function sourceDir(): string {
  return join(import.meta.dirname, '..', 'src');
}
