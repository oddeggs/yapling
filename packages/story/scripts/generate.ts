import { readdirSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';

/*
 * Compiles `audio/season-1/lines.json` into two modules:
 * - `src/lines.generated.ts`: the line data, safe to import anywhere (the call server too): each
 *   recorded line (`lines`: caption from its timing file, duration, file names) and each written
 *   line still waiting for its recording (`pending`: caption from its voice text, no audio). Scenes
 *   name lines by id, so moving a line from `pending` to `lines` needs no scene edit;
 * - `src/assets.generated.ts`: static `require()`s of each line's mp3 and timing file, for Metro to
 *   bundle (app only, imported as `@yapling/story/assets`).
 * Audio stays in the repo's `audio/` directory; nothing is copied.
 */

export const PACKAGE_DIR = join(import.meta.dirname, '..');
export const REPO_DIR = join(PACKAGE_DIR, '..', '..');
export const LINES_DIR = join(REPO_DIR, 'audio', 'season-1', 'lines');
export const LINES_JSON = join(REPO_DIR, 'audio', 'season-1', 'lines.json');
export const SFX_DIR = join(REPO_DIR, 'audio', 'season-1', 'sfx');

export const LINES_MODULE = 'src/lines.generated.ts';
export const ASSETS_MODULE = 'src/assets.generated.ts';

interface SourceLine {
  readonly id: string;
  readonly char: string;
  readonly text: string;
  readonly kind?: string;
  readonly take?: string;
  readonly name_splice?: string;
  readonly lang?: string;
  readonly speed?: number;
  /** The line's Vietnamese gloss, written beside it in the script (a draft until reviewed). */
  readonly _vi?: string;
}

interface Source {
  readonly lines: readonly SourceLine[];
  readonly pending?: readonly SourceLine[];
}

interface SourceTiming {
  readonly caption: string;
  readonly alignment: { readonly character_end_times_seconds: readonly number[] };
}

const readJson = <T>(path: string): T => JSON.parse(readFileSync(path, 'utf8')) as T;

export const lineFiles = (line: { readonly id: string; readonly char: string }) => ({
  mp3: `${line.id}-${line.char}.mp3`,
  timing: `${line.id}-${line.char}.timing.json`,
});

const HEADER =
  '// Generated by `pnpm --filter @yapling/story gen` from audio/season-1. Do not edit.\n';

/** The voice text without its Eleven v4 tags (`[whispers]`, `[pause]`): a pending line's caption. */
export const captionOf = (text: string): string =>
  text
    .replace(/\[[^\]]*\]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

/** The fields every written line shares, recorded or pending. */
const written = (line: SourceLine) => ({
  id: line.id,
  character: line.char,
  text: line.text,
  kind: line.kind ?? 'scene',
  take: line.take ?? null,
  nameSplice: line.name_splice ?? null,
  language: line.lang ?? 'en',
  speed: line.speed ?? null,
  vi: line._vi ?? null,
});

/** The two generated modules, by path relative to the package. */
export const generate = (): Record<string, string> => {
  const { lines: source, pending: waiting = [] } = readJson<Source>(LINES_JSON);
  const recordedIds = new Set(source.map((line) => line.id));
  const twice = waiting.filter((line) => recordedIds.has(line.id)).map((line) => line.id);
  if (twice.length > 0) {
    throw new Error(`Recorded and still pending in lines.json: ${twice.join(', ')}`);
  }

  const records = source.map((line) => {
    const files = lineFiles(line);
    const timing = readJson<SourceTiming>(join(LINES_DIR, files.timing));
    const ends = timing.alignment.character_end_times_seconds;
    const { id, character, text, ...rest } = written(line);
    return {
      id,
      character,
      text,
      caption: timing.caption,
      ...rest,
      audio: {
        mp3: files.mp3,
        timing: files.timing,
        durationMs: Math.round((ends[ends.length - 1] ?? 0) * 1000),
      },
    };
  });

  const pending = waiting.map((line) => {
    const { id, character, text, ...rest } = written(line);
    return { id, character, text, caption: captionOf(line.text), ...rest, audio: null };
  });

  const idList = (rows: readonly { id: string }[]) =>
    rows.map((r) => `  ${JSON.stringify(r.id)},`).join('\n');
  const dataList = (rows: readonly object[]) =>
    rows.map((r) => `  ${JSON.stringify(r)},`).join('\n');
  const lines = `${HEADER}import type { PendingLineData, RecordedLineData } from './types';

export const RECORDED_LINE_IDS = [
${idList(records)}
] as const;
export type RecordedLineId = (typeof RECORDED_LINE_IDS)[number];

export const RECORDED_LINES: readonly RecordedLineData[] = [
${dataList(records)}
];

/** Written in lines.json, not recorded yet: the call speaks them with the live voice until then. */
export const PENDING_LINE_IDS = [
${idList(pending)}
] as const;
export type PendingLineId = (typeof PENDING_LINE_IDS)[number];

export const PENDING_LINES: readonly PendingLineData[] = [
${dataList(pending)}
];
`;

  const fromSrc = relative(join(PACKAGE_DIR, 'src'), LINES_DIR).split('\\').join('/');
  const entries = records
    .map((r) => {
      const mp3 = JSON.stringify(`${fromSrc}/${r.audio.mp3}`);
      const timing = JSON.stringify(`${fromSrc}/${r.audio.timing}`);
      return `  ${JSON.stringify(r.id)}: {
    audio: () => require(${mp3}) as number,
    timing: () => require(${timing}) as LineTiming,
  },`;
    })
    .join('\n');
  const sfxFromSrc = relative(join(PACKAGE_DIR, 'src'), SFX_DIR).split('\\').join('/');
  const sfx = readdirSync(SFX_DIR)
    .filter((name) => name.endsWith('.mp3'))
    .sort()
    .map((name) => {
      const path = JSON.stringify(`${sfxFromSrc}/${name}`);
      return `  ${JSON.stringify(name.replace(/\.mp3$/, ''))}: () => require(${path}) as number,`;
    })
    .join('\n');
  const assets = `${HEADER}// Metro bundles every file required here; each getter loads its module on first use.
import type { RecordedLineId } from './lines.generated';
import type { LineTiming, SfxId } from './types';

export interface RecordedLineAsset {
  /** The bundled mp3 (a Metro asset id). */
  readonly audio: () => number;
  readonly timing: () => LineTiming;
}

export const RECORDED_LINE_ASSETS: Readonly<Record<RecordedLineId, RecordedLineAsset>> = {
${entries}
};

/** Sound effects (Metro asset ids). */
export const SFX_ASSETS: Readonly<Record<SfxId, () => number>> = {
${sfx}
};
`;

  return { [LINES_MODULE]: lines, [ASSETS_MODULE]: assets };
};
