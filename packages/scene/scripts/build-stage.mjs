// Builds the stage page (the painted scene the app shows in a web view) into one TypeScript string.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const html = [
  read('stage/stage.html'),
  read('paint/core.js'),
  read('paint/cast.js'),
  read('paint/places.js'),
  read('stage/stage.js'),
].join('\n');
mkdirSync(join(root, 'stage/dist'), { recursive: true });
writeFileSync(join(root, 'stage/dist/index.html'), html);
writeFileSync(
  join(root, 'src/stage-html.generated.ts'),
  `// Generated by scripts/build-stage.mjs from paint/ and stage/. Do not edit.\nexport const STAGE_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`stage: ${(html.length / 1024).toFixed(0)} KB`);
